#!/usr/bin/env bash
# Builds FireSafari: Firefox for Android (Fenix) with the patches in patches/, on Mozilla's
# prebuilt release GeckoView. No Gecko C++ is compiled.
#
# Moving to a newer Firefox: set FIREFOX_TAG and GECKOVIEW_VERSION (they must be the same
# release), delete firefox/, run this again, and fix any patch that no longer applies.
set -euo pipefail

FIREFOX_TAG=${FIREFOX_TAG:-FIREFOX_157_0_1_RELEASE}
# The matching engine build: maven.mozilla.org/maven2/org/mozilla/geckoview/geckoview-omni/
GECKOVIEW_VERSION=${GECKOVIEW_VERSION:-157.0.20261005135250}

HERE=$(cd "$(dirname "$0")" && pwd)
SRC=$HERE/firefox
export MOZCONFIG=$HERE/mozconfig
export ANDROID_HOME=${ANDROID_HOME:-$HOME/Android/Sdk}
export JAVA_HOME=${JAVA_HOME:-$HOME/.jdks/jdk-21.0.12.1+1}
export PATH=$JAVA_HOME/bin:$PATH

fail() { echo "build.sh: $*" >&2; exit 1; }

# --- Prerequisites that mach configure checks for (see README) -------------------------------
[ -x "$JAVA_HOME/bin/java" ] || fail "no JDK at JAVA_HOME=$JAVA_HOME (use JDK 17 or 21)"
[ -x "$ANDROID_HOME/cmdline-tools/21.0/bin/sdkmanager" ] ||
    fail "mach needs $ANDROID_HOME/cmdline-tools/21.0 (a symlink to cmdline-tools/latest works)"
[ -d "$ANDROID_HOME/platforms/android-37.1" ] || fail "install the Android SDK platform android-37.1"
[ -f "$HOME/.mozbuild/bundletool.jar" ] ||
    fail "download bundletool 1.18.3 to ~/.mozbuild/bundletool.jar (see README)"

# --- Source: the Firefox release, with the FireSafari patches applied ------------------------
if [ ! -d "$SRC/.git" ]; then
    git clone --depth 1 --branch "$FIREFOX_TAG" --single-branch \
        https://github.com/mozilla-firefox/firefox.git "$SRC"
fi
cd "$SRC"
for patch in "$HERE"/patches/*.patch; do
    if git apply --reverse --check "$patch" 2>/dev/null; then
        echo "already applied: $(basename "$patch")"
    else
        git apply --whitespace=nowarn "$patch" || fail "$(basename "$patch") does not apply to $FIREFOX_TAG"
        echo "applied: $(basename "$patch")"
    fi
done

# --- Configure (once): Gradle reads the result from objdir-firesafari/ ------------------------
OBJDIR=$SRC/objdir-firesafari
if [ ! -f "$OBJDIR/config.status.json" ]; then
    ./mach --no-interactive configure
    ./mach build-backend
fi

# A few sources are generated by mach, not Gradle: the crash-report annotations and the
# web-compat add-on. Build only those targets (a full `mach build` would fetch prebuilt Gecko).
grep -oE '^\$\(TOPOBJDIR\)/mobile/android/(webcompat_addon_generated_files|android-components/components/lib/crash)/[^ :]*\.stub:' \
    "$OBJDIR/faster/Makefile" |
    sed -e 's/:$//' -e "s|\$(TOPOBJDIR)|$OBJDIR|" -e 's|\$(MDDEPDIR)|.deps|' |
    xargs make -s -C "$OBJDIR/faster"

# --- Build ------------------------------------------------------------------------------------
# Fenix's own Gradle settings (7 GB heap, parallel builds, R8 shrinking) need a big machine.
# These defaults fit in about 6 GB of free RAM. On a bigger machine raise GRADLE_HEAP and
# GRADLE_WORKERS, and set SHRINK=1 for a smaller APK (R8 needs a lot of memory).
GRADLE_HEAP=${GRADLE_HEAP:-5g}
GRADLE_WORKERS=${GRADLE_WORKERS:-2}
gradle_args=(
    --max-workers="$GRADLE_WORKERS" --no-parallel
    "-Dorg.gradle.jvmargs=-Xmx$GRADLE_HEAP -Xms1g -XX:MaxMetaspaceSize=1536m -XX:+UseParallelGC"
    -Pkotlin.compiler.execution.strategy=in-process
    -PgeckoviewVersion="$GECKOVIEW_VERSION"
    -PversionName="$(cat "$SRC/browser/config/version_display.txt")"
)
[ "${SHRINK:-0}" = 1 ] || gradle_args+=(-PdisableOptimization)

cd mobile/android/fenix
# The build date becomes the version code, so every build installs over the previous one.
MOZ_BUILD_DATE=$(date -u +%Y%m%d%H%M%S) ./gradlew "${gradle_args[@]}" :app:assembleRelease

echo
echo "APKs (signed with this machine's debug key):"
ls -1 "$OBJDIR"/gradle/build/mobile/android/fenix/app/outputs/apk/release/*.apk
